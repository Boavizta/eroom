#!/usr/bin/env python3
"""Deployment freshness and atomicity indicators, from the `.har`.

Why this module: the indicator used until now for EOF criterion 6.3
("Is there an effective CI/CD process?") relied on
`sitemap.days_since_lastmod`. Verified on octo.com on 2026-09-03: the site
has **no** `sitemap.xml` (0 `<loc>` tags), so the indicator produced nothing
at all. The `Last-Modified` headers of 1st-party resources, already present
in the `.har`, give a richer signal that is available far more often.

Three signals extracted, no network call:

1. **Freshness**: age of the most recent 1st-party resource, measured
   against the HAR capture date (and not against now: a July HAR analyzed in
   September would otherwise give a falsely high age).
2. **Atomicity**: dispersion of `Last-Modified` across 1st-party resources,
   measured **only on code resources** (HTML, CSS, JS). A dispersion of a few
   seconds signals a publication in a single block (full rebuild then atomic
   go-live), a pattern typical of an automated pipeline. A dispersion of
   several months signals files dropped one by one.

   Images, fonts and media are **excluded** from this computation. Verified
   on octo.com: measured over all resources, the dispersion reaches 644 days,
   because images keep their original upload date (2024) while code is
   regenerated at each build. Mixing the two does not measure deployment
   atomicity but content age, which answers a different question.
3. **Declared build timestamp**: anti-cache parameters of the form
   `?v=2026-6-10-1-1`. When the value is dated, it is compared to the
   `Last-Modified` of the same resource; a match indicates the parameter is
   generated by the build pipeline itself.

What these signals do NOT prove, and why this criterion stays an indicator
never automatically checked:

- A tight dispersion is also the result of an `rsync` or a manual drop of the
  full tree. Atomicity is not automation.
- A recent deployment says nothing about the **frequency** of deployments.
  Two audits spaced in time would be needed to talk about cadence.
- A night-time publication hour is suggestive of a scheduled task,
  not proof: nothing prevents publishing by hand at 1 a.m.

Verification of the dated-parameter decoding (octo.com, two independent
observations): the HAR of 2026-07-10 carries `?v=2026-6-10-1-1` with a
`Last-Modified` of 2026-07-10 01:01:26, and a `curl` of 2026-09-03 returns
`?v=2026-8-3-1-1` with a `Last-Modified` of 2026-09-03 01:01:31. The month is
therefore 0-indexed (behavior of JavaScript's `Date.getMonth()`), and the
format is year-month-day-hour-minute. Both observations match the
`Last-Modified` exactly, which makes the interpretation reliable for this
site. Decoding is still attempted tolerantly: on failure, no value is
invented.

Usage as a module:
    from deploy_freshness import analyze_har_freshness
    info = analyze_har_freshness(har_path, first_party_hosts)

Command-line usage (inspection):
    python3 deploy_freshness.py <source_dir>
"""

import argparse
import json
import re
import sys
from datetime import datetime, timezone
from email.utils import parsedate_to_datetime
from pathlib import Path
from urllib.parse import urlparse, parse_qs

RAW_DATA_DIR = "raw-data-potentially-sensitive"

# Query parameters commonly used as build anti-cache.
_VERSION_PARAMS = ("v", "ver", "version", "rev", "build", "t", "_")

# A build timestamp of the form YYYY-M-D[-H-M], month possibly 0-indexed.
# Deliberately wide bounds: validation is done by matching Last-Modified,
# not by the shape alone.
_DATED_VERSION_RE = re.compile(r"^(\d{4})-(\d{1,2})-(\d{1,2})(?:-(\d{1,2})-(\d{1,2}))?$")

# Resources regenerated at each build (thus carrying the deployment date),
# as opposed to media uploaded once and for all.
_CODE_MIME_HINTS = ("html", "javascript", "ecmascript", "css", "json", "xml")
_CODE_EXTENSIONS = (".html", ".htm", ".js", ".mjs", ".css", ".json", ".xml", ".txt", ".map")


def _is_code_resource(url, mime_type):
    """True if the resource is code regenerated at build, not an uploaded medium."""
    if mime_type:
        lowered = mime_type.lower()
        # The media test comes BEFORE the code hints: `image/svg+xml`
        # contains "xml" yet it is an uploaded medium, not build code.
        if lowered.startswith(("image/", "font/", "video/", "audio/")):
            return False
        if any(hint in lowered for hint in _CODE_MIME_HINTS):
            return True
    path = urlparse(url).path.lower()
    if path.endswith(_CODE_EXTENSIONS):
        return True
    if "." not in path.rsplit("/", 1)[-1]:
        return True  # extensionless URL: server-rendered or static page
    return False


def find_har(source_dir):
    hars = list(source_dir.glob("*.har")) or list((source_dir / RAW_DATA_DIR).glob("*.har"))
    return hars[0] if hars else None


def _parse_http_date(value):
    try:
        dt = parsedate_to_datetime(value)
    except (TypeError, ValueError, IndexError):
        return None
    if dt is None:
        return None
    return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)


def _har_capture_date(har):
    """HAR capture date, from the first page. None if unavailable."""
    pages = har.get("log", {}).get("pages") or []
    for page in pages:
        started = page.get("startedDateTime")
        if started:
            try:
                return datetime.fromisoformat(started.replace("Z", "+00:00"))
            except ValueError:
                continue
    return None


def _first_party_hosts_from_env(source_dir):
    """1st-party hosts, deduced from the pages listed in env-data.json."""
    env_path = source_dir / "env-data.json"
    if not env_path.exists():
        return set()
    env = json.loads(env_path.read_text(encoding="utf-8"))
    hosts = set()
    for page in env.get("pages") or []:
        url = page.get("url")
        if url:
            host = urlparse(url).netloc.lower()
            if host:
                hosts.add(host)
    return hosts


def _decode_dated_version(raw):
    """'2026-6-10-1-1' -> (datetime month 0-indexed, datetime month 1-indexed).

    Returns both possible readings, without choosing: it is the match with
    Last-Modified that decides. (None, None) if the shape does not fit.
    """
    match = _DATED_VERSION_RE.match(raw.strip())
    if not match:
        return None, None
    year, month, day = int(match.group(1)), int(match.group(2)), int(match.group(3))
    hour = int(match.group(4)) if match.group(4) else 0
    minute = int(match.group(5)) if match.group(5) else 0
    candidates = []
    for month_value in (month + 1, month):  # 0-indexed month, then 1-indexed month
        if not 1 <= month_value <= 12 or not 1 <= day <= 31 or hour > 23 or minute > 59:
            candidates.append(None)
            continue
        try:
            candidates.append(datetime(year, month_value, day, hour, minute, tzinfo=timezone.utc))
        except ValueError:
            candidates.append(None)
    return candidates[0], candidates[1]


def _extract_version_stamp(url, last_modified):
    """Looks for a dated version parameter and checks whether it matches Last-Modified.

    Returns None if no dated parameter, otherwise a dict describing the
    match. 5-minute tolerance: the parameter is usually frozen at the start
    of the build, the files written a few seconds later.
    """
    query = parse_qs(urlparse(url).query)
    for param in _VERSION_PARAMS:
        for raw in query.get(param, []):
            base0, base1 = _decode_dated_version(raw)
            if base0 is None and base1 is None:
                continue
            entry = {
                "parametre": f"{param}={raw}",
                "lecture_mois_indexe_0": base0.isoformat() if base0 else None,
                "lecture_mois_indexe_1": base1.isoformat() if base1 else None,
                "concorde_avec_last_modified": None,
                "delta_seconds": None,
            }
            if last_modified is not None:
                best = None
                for label, candidate in (("month 0-indexed", base0), ("month 1-indexed", base1)):
                    if candidate is None:
                        continue
                    delta = abs((candidate - last_modified).total_seconds())
                    if best is None or delta < best[1]:
                        best = (label, delta)
                if best is not None:
                    entry["delta_seconds"] = round(best[1])
                    entry["concorde_avec_last_modified"] = best[0] if best[1] <= 300 else None
            return entry
    return None


def analyze_har_freshness(har_path, first_party_hosts=None):
    """Deployment freshness/atomicity indicators. None if nothing exploitable."""
    with open(har_path, encoding="utf-8") as f:
        har = json.load(f)

    capture_date = _har_capture_date(har)
    entries = har.get("log", {}).get("entries") or []

    observed = []
    for entry in entries:
        url = entry.get("request", {}).get("url") or ""
        host = urlparse(url).netloc.lower()
        if not host:
            continue
        if first_party_hosts and host not in first_party_hosts:
            continue
        response = entry.get("response", {})
        headers = {h["name"].lower(): h["value"] for h in response.get("headers") or []}
        last_modified = _parse_http_date(headers.get("last-modified"))
        if last_modified is None:
            continue
        mime_type = (response.get("content") or {}).get("mimeType")
        observed.append({
            "url": url, "last_modified": last_modified,
            "est_code": _is_code_resource(url, mime_type),
        })

    if not observed:
        return None

    observed.sort(key=lambda o: o["last_modified"])
    code_only = [o for o in observed if o["est_code"]]
    # Atomicity is measured on code only; failing to identify code, we do not
    # compute a dispersion rather than compute a misleading one.
    if code_only:
        spread_seconds = (code_only[-1]["last_modified"] - code_only[0]["last_modified"]).total_seconds()
        newest = code_only[-1]
    else:
        spread_seconds = None
        newest = observed[-1]
    oldest = observed[0]

    version_stamp = None
    for item in observed:
        stamp = _extract_version_stamp(item["url"], item["last_modified"])
        if stamp is not None:
            version_stamp = {**stamp, "url": item["url"]}
            break

    reference = capture_date or datetime.now(timezone.utc)
    age_days = (reference - newest["last_modified"]).total_seconds() / 86400

    return {
        "ressources_1st_party_avec_last_modified": len(observed),
        "ressources_de_code": len(code_only),
        "plus_recente": {
            "url": newest["url"],
            "last_modified": newest["last_modified"].isoformat(),
        },
        "plus_ancienne": {
            "url": oldest["url"],
            "last_modified": oldest["last_modified"].isoformat(),
        },
        "dispersion_code_secondes": round(spread_seconds) if spread_seconds is not None else None,
        "age_jours_vs_capture": round(age_days, 2),
        "reference_age": "HAR capture date" if capture_date else "now (HAR capture date not found)",
        "heure_publication_utc": newest["last_modified"].strftime("%H:%M"),
        "build_declared_at": version_stamp,
        "note": (
            "Freshness and atomicity indicators, never proof of CI/CD: "
            "a tight dispersion can result from a manual drop of the "
            "full tree, and a recent deployment says nothing about "
            "the frequency of deployments."
        ),
    }


def summarize(info):
    """Short sentence for the report appendix. None if info is None."""
    if not info:
        return None
    # This text is read by the audited service, in the questionnaire and in the
    # report: it is written for them, without our tooling vocabulary.
    parts = [
        f"most recent resource of your site: {info['age_jours_vs_capture']:.1f} day(s) "
        f"before the capture (published at {info['heure_publication_utc']} UTC)"
    ]
    spread = info["dispersion_code_secondes"]
    if spread is None:
        parts.append("no code resource identified: atomicity not measurable")
    elif spread <= 300:
        parts.append(
            f"the {info['ressources_de_code']} code resources (HTML/CSS/JS) are "
            f"published within {spread} s (go-live in a single block)"
        )
    else:
        parts.append(
            f"code publication dispersion: {spread / 86400:.1f} day(s) "
            "(staggered go-lives)"
        )
    stamp = info.get("build_declared_at")
    if stamp and stamp.get("concorde_avec_last_modified"):
        parts.append(
            f"your file addresses carry a date ({stamp['parametre']}) that "
            f"matches within {stamp['delta_seconds']} s the last-modified date "
            "declared by your server, hence produced by your build "
            "pipeline"
        )
    elif stamp:
        parts.append(
            f"your file addresses carry a date ({stamp['parametre']}) that does "
            "not match the last-modified date declared by your server"
        )
    return " ; ".join(parts)


# French-named alias kept for run_eof.py, which imports `summarise` until it is translated.
summarise = summarize


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source_dir")
    args = parser.parse_args()
    source_dir = Path(args.source_dir).resolve()

    har_path = find_har(source_dir)
    if not har_path:
        print(f"Error: no .har in {source_dir} (nor in {RAW_DATA_DIR}/).")
        sys.exit(1)

    hosts = _first_party_hosts_from_env(source_dir)
    info = analyze_har_freshness(har_path, hosts or None)
    if info is None:
        print("No 1st-party resource with a Last-Modified header: indicator unavailable.")
        sys.exit(0)

    print(f"HAR: {har_path.name}")
    print(f"1st-party hosts kept: {sorted(hosts) or '(all, env-data.json absent)'}")
    print(json.dumps(info, ensure_ascii=False, indent=2))
    print(f"\nSummary: {summarize(info)}")


if __name__ == "__main__":
    main()
